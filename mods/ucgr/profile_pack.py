"""Deduplicate literal extension data inside this pack's own schema module.

The host still validates the expanded configuration through every ordinary
capability schema. No definition, asset or executable content lives elsewhere.
"""
from collections import Counter
from copy import deepcopy
from hashlib import sha256
import json


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))


def expand_profiles(value, root):
    """Source-tool view; distribution readers use the pack schema's validator."""
    profiles = json.loads((root / 'literal-profiles.json').read_text())
    def expand(item):
        if isinstance(item, dict):
            if '$ucgr' in item:
                if len(item) != 1 or item['$ucgr'] not in profiles:
                    raise ValueError('Unknown UCGR literal profile')
                return expand(profiles[item['$ucgr']])
            return {key: expand(child) for key, child in item.items()}
        if isinstance(item, list):
            return [expand(child) for child in item]
        return item
    return expand(value)


def pack_profiles(definitions, root):
    counts = Counter()

    def collect(value):
        if not isinstance(value, (dict, list)):
            return
        encoded = canonical(value)
        if len(encoded) >= 350:
            counts[encoded] += 1
        for child in value.values() if isinstance(value, dict) else value:
            collect(child)

    owners = [owner for definition in definitions for owner in [definition] + definition.get('weapons', [])]
    for owner in owners:
        for config in owner.get('extensions', {}).values():
            collect(config)
    ids = {value: sha256(value.encode()).hexdigest()[:20] for value, count in sorted(counts.items()) if count > 1}
    assert len(set(ids.values())) == len(ids), 'literal profile hash collision'

    def compress(value, self_key=None):
        if isinstance(value, (dict, list)):
            key = canonical(value)
            if key in ids and key != self_key:
                return {'$ucgr': ids[key]}
        if isinstance(value, dict):
            return {key: compress(child) for key, child in value.items()}
        if isinstance(value, list):
            return [compress(child) for child in value]
        return value

    profiles = {id_: compress(json.loads(value), value) for value, id_ in ids.items()}
    (root / 'literal-profiles.json').write_text(canonical(profiles)+'\n')
    path = root / 'extensions/combined-arms-v1/src/generatedProfiles.ts'
    path.write_text('// Generated by profile_pack.py; original literal data, never source expressions.\n'
                    'export const sourceProfiles: Record<string, unknown> = ' + canonical(profiles) + ';\n')
    output = deepcopy(definitions)
    for definition in output:
        for owner in [definition] + definition.get('weapons', []):
            if 'extensions' in owner:
                owner['extensions'] = {key: compress(value) for key, value in owner['extensions'].items()}
    return output, {'profiles': len(profiles), 'before': len(canonical(definitions)),
                    'after': len(canonical(output)), 'table': len(canonical(profiles))}
